/**
 * What a term mark names, a link whose text sits between single asterisks, and
 * the rotting the checker reports for a term mark that names no term or whose
 * words spell no form of it.
 */
import { describe, expect, it } from 'vitest';
import { canon, check, tagged } from './project.ts';

const LEAF = `
### @spec a-leaf-says-one-thing

> A leaf says one thing.
`;

describe('a term mark', () => {
  const TEST = tagged('spec-a-leaf-says-one-thing');
  const TERM = `\n## @term outdated-tracking\n\n> An outdated tracking is a finding.\n`;
  /** The leaf, a sentence after it, and the term `term-outdated-tracking`. */
  const marked = (sentence: string): string => canon(`${LEAF}\n${sentence}\n${TERM}`);

  /**
   * @canon spec-a-term-mark-names-a-term
   */
  it('reports a rotting for a term mark in a link to a unit that is no term', async () => {
    expect((await check(marked('See [*a leaf*](#spec-a-leaf-says-one-thing).'), TEST))['rot']).toBe(1);
  });

  /**
   * @canon spec-a-term-with-no-grammar-table-has-the-words-of-its-stem-as-its-only-form
   */
  it('reports a rotting for a term mark whose words spell no form of its term', async () => {
    expect((await check(marked('A bug can have an [*outdated trackings*](#term-outdated-tracking).'), TEST))['rot']).toBe(1);
  });

  /**
   * @canon spec-a-term-with-no-grammar-table-has-the-words-of-its-stem-as-its-only-form
   */
  it('reports no rotting for a term mark whose words spell the stem of its term', async () => {
    expect((await check(marked('A bug can have an [*outdated tracking*](#term-outdated-tracking).'), TEST))['rot']).toBeUndefined();
  });

  /**
   * @canon spec-a-term-mark-names-its-term-whatever-its-case
   */
  it('reports no rotting for a term mark that spells a form in capitals', async () => {
    expect((await check(marked('[*Outdated tracking*](#term-outdated-tracking) is a finding.'), TEST))['rot']).toBeUndefined();
  });

  /**
   * @canon spec-a-term-mark-names-a-term-of-another-document-through-its-link
   */
  it('names a term of another document through its link', async () => {
    const extending = `---\nextends: ["./glossary.md"]\n---\n${canon(`${LEAF}\nA bug can have an [*outdated tracking*](./glossary.md#term-outdated-tracking).\n`)}`;
    const glossary = `# Glossary\n\n<!-- toc:begin — generated by \`canon generate\`; edits are overwritten -->\n<!-- toc:end -->\n${TERM}`;
    expect((await check(extending, TEST, { files: { 'glossary.md': glossary } }))['rot']).toBeUndefined();
    const misspelled = extending.replace('[*outdated tracking*]', '[*outdated trackings*]');
    expect((await check(misspelled, TEST, { files: { 'glossary.md': glossary } }))['rot']).toBe(1);
  });

  /**
   * @canon spec-single-asterisks-outside-a-link-are-emphasis
   */
  it('reads single asterisks outside a link as emphasis, which names nothing', async () => {
    expect((await check(marked('A bug can have an *outdated trackings*, and [*outdated tracking*](#term-outdated-tracking) is a finding.'), TEST))['rot']).toBeUndefined();
  });
});
