/**
 * What a term mark names, and the rotting the checker reports for a term mark
 * that names no term.
 */
import { describe, expect, it } from 'vitest';
import { canon, check, tagged } from './project.ts';

const LEAF = `
### @spec a-leaf-says-one-thing

> A leaf says one thing.
`;

describe('a term mark', () => {
  const TEST = tagged('spec-a-leaf-says-one-thing');
  const TERM = `\n## @term outdated-tracking\n\n> An outdated tracking is a finding.\n`;
  /** The leaf, a sentence after it, and the term `term-outdated-tracking`. */
  const marked = (sentence: string): string => canon(`${LEAF}\n${sentence}\n${TERM}`);

  /**
   * @canon spec-a-term-mark-names-a-term
   */
  it('reports a rotting for a term mark whose words spell no stem', async () => {
    expect((await check(marked('A bug can have an *outdated trackings*.'), TEST))['rot']).toBe(1);
  });

  /**
   * @canon spec-a-term-mark-names-the-term-whose-stem-its-words-spell
   */
  it('reports no rotting for a term mark whose words spell the stem of a term', async () => {
    expect((await check(marked('A bug can have an *outdated tracking*.'), TEST))['rot']).toBeUndefined();
  });

  /**
   * @canon spec-a-term-mark-names-its-term-whatever-its-case
   */
  it('reports no rotting for a term mark that spells a stem in capitals', async () => {
    expect((await check(marked('*Outdated tracking* is a finding.'), TEST))['rot']).toBeUndefined();
  });

  /**
   * @canon spec-a-term-mark-in-a-link-names-the-target-of-the-link
   */
  it('reports no rotting for a term mark in a link to a term, whatever its words spell', async () => {
    expect((await check(marked('Bugs can have [*outdated trackings*](#term-outdated-tracking).'), TEST))['rot']).toBeUndefined();
  });

  /**
   * @canon spec-a-term-mark-in-a-link-names-the-target-of-the-link
   */
  it('reports a rotting for a term mark in a link to a unit that is no term', async () => {
    expect((await check(marked('See [*a leaf*](#spec-a-leaf-says-one-thing).'), TEST))['rot']).toBe(1);
  });

  /**
   * @canon spec-a-term-mark-names-no-term-of-another-document
   */
  it('reports a rotting for a term mark whose stem only a document it extends declares', async () => {
    const extending = `---\nextends: ["./glossary.md"]\n---\n${canon(`${LEAF}\nA bug can have an *outdated tracking*.\n`)}`;
    const glossary = `# Glossary\n\n<!-- toc:begin — generated by \`canon generate\`; edits are overwritten -->\n<!-- toc:end -->\n${TERM}`;
    expect((await check(extending, TEST, { files: { 'glossary.md': glossary } }))['rot']).toBe(1);
  });
});
